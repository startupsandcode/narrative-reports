import PDFDocument from "pdfkit";
import type { Client, Narrative } from "./types";
import { money, num, pct } from "./narrative";

/**
 * Render a white-labeled PDF report for a client.
 * White-label inputs: agencyName + primaryColor (logo support: v2).
 * Returns the PDF as a Buffer.
 */
export function renderReportPdf(client: Client, narrative: Narrative): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const chunks: Buffer[] = [];
    const doc = new PDFDocument({ size: "A4", margin: 56, autoFirstPage: false });

    doc.on("data", (c: Buffer) => chunks.push(c));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    const primary = sanitizeColor(client.primaryColor);
    const gray = "#6b7280";
    const dark = "#111827";

    // Page geometry lives on doc.page, which is null until the first addPage()
    // (autoFirstPage: false). All helpers read these after addPage() has run.
    const geo = { pageW: 0, margin: 56, contentW: 0 };

    // Footer is drawn once per page via a single pageAdded listener. Footer
    // text sits below the normal bottom margin, so the margin is temporarily
    // zeroed while drawing it — otherwise pdfkit's overflow check would add
    // another page, re-fire pageAdded, and recurse forever.
    const footer = () => {
      const { margin, contentW } = geo;
      const page = doc.page;
      const prevBottom = page.margins.bottom;
      page.margins.bottom = 0;
      doc.fillColor(gray).font("Helvetica").fontSize(8);
      doc.text(
        `Prepared for ${client.name} · White-labeled for ${client.agencyName} · Generated by Narrative Reports`,
        margin,
        page.height - 40,
        { width: contentW, align: "center" }
      );
      page.margins.bottom = prevBottom;
    };
    doc.on("pageAdded", footer);

    const addPage = () => {
      doc.addPage();
      geo.pageW = doc.page.width;
      geo.margin = 56;
      geo.contentW = doc.page.width - geo.margin * 2;
      const { margin, contentW, pageW } = geo;

      // white-label header band
      doc.rect(0, 0, pageW, 76).fill(primary);
      doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(17);
      doc.text(client.agencyName, margin, 26, { width: contentW });
      doc.fillColor("#ffffff").font("Helvetica").fontSize(9.5);
      doc.text(`Monthly Performance Report · ${narrative.periodLabel}`, margin, 48, {
        width: contentW,
      });
      // footer is drawn by the pageAdded listener above — do not call it here
      // or it renders twice.
      doc.y = 104;
    };

    const section = (title: string) => {
      const { margin, contentW } = geo;
      if (doc.y > doc.page.height - 140) addPage();
      doc.fillColor(primary).font("Helvetica-Bold").fontSize(13);
      doc.text(title, margin, doc.y, { width: contentW });
      doc.moveDown(0.4);
      doc.strokeColor(primary).lineWidth(1.5);
      doc.moveTo(margin, doc.y).lineTo(margin + 44, doc.y).stroke();
      doc.moveDown(0.6);
    };

    const body = (text: string) => {
      const { margin, contentW } = geo;
      if (doc.y > doc.page.height - 100) addPage();
      doc.fillColor(dark).font("Helvetica").fontSize(10.5);
      doc.text(text, margin, doc.y, { width: contentW, lineGap: 3 });
      doc.moveDown(0.7);
    };

    const bullets = (items: string[]) => {
      const { margin, contentW } = geo;
      for (const item of items) {
        if (doc.y > doc.page.height - 110) addPage();
        doc.fillColor(dark).font("Helvetica").fontSize(10.5);
        doc.circle(margin + 4, doc.y + 5, 2.2).fill(primary);
        doc.fillColor(dark);
        doc.text(item, margin + 14, doc.y, { width: contentW - 14, lineGap: 3 });
        doc.moveDown(0.7);
      }
    };

    // ---- Page 1 ----
    addPage();
    const { margin, contentW } = geo;

    doc.fillColor(dark).font("Helvetica-Bold").fontSize(22);
    doc.text(client.name, margin, doc.y, { width: contentW });
    doc.moveDown(0.3);
    doc.fillColor(gray).font("Helvetica").fontSize(11);
    doc.text(narrative.headline, margin, doc.y, { width: contentW, lineGap: 2 });
    doc.moveDown(1.0);

    // KPI grid (4 across, wrapping to 2 rows)
    const m = narrative.metrics;
    const kpis: Array<[string, string]> = [
      ["Total spend", money(m.totalSpend)],
      ["Impressions", num(m.totalImpressions)],
      ["Clicks", num(m.totalClicks)],
      ["Conversions", num(m.totalConversions)],
      ["Click-through rate", pct(m.ctr)],
      ["Avg. cost / click", money(m.avgCpc)],
      ["Cost / conversion", m.totalConversions > 0 ? money(m.costPerConversion) : "—"],
      ["Campaigns", String(m.campaignCount)],
    ];
    const cols = 4;
    const cellW = contentW / cols;
    let startY = doc.y;
    kpis.forEach(([label, value], i) => {
      const col = i % cols;
      if (col === 0 && i > 0) {
        startY = doc.y + 8;
      }
      const x = margin + col * cellW;
      const y = startY;
      doc.rect(x + 2, y, cellW - 4, 52).fill("#f3f4f6");
      doc.fillColor(gray).font("Helvetica").fontSize(8);
      doc.text(label.toUpperCase(), x + 10, y + 8, { width: cellW - 20 });
      doc.fillColor(dark).font("Helvetica-Bold").fontSize(13);
      doc.text(value, x + 10, y + 24, { width: cellW - 20 });
      if (col === cols - 1 || i === kpis.length - 1) {
        doc.y = y + 52;
      }
    });
    doc.y = startY + 52 + 14;

    section("Summary");
    narrative.summary.forEach(body);

    section("Wins");
    bullets(narrative.wins);

    section("Recommendations");
    bullets(narrative.recommendations);

    if (client.rows.length > 0) {
      section("Campaign detail");
      const colW = [contentW * 0.36, contentW * 0.14, contentW * 0.14, contentW * 0.1, contentW * 0.12, contentW * 0.14];
      const headers = ["Campaign", "Spend", "Impressions", "Clicks", "Conv.", "CTR"];
      doc.fillColor("#ffffff").font("Helvetica-Bold").fontSize(9);
      doc.rect(margin, doc.y, contentW, 22).fill(primary);
      headers.forEach((h, i) => {
        const x = margin + colW.slice(0, i).reduce((a, b) => a + b, 0);
        doc.text(h, x + 6, doc.y + 6, { width: colW[i] - 12 });
      });
      doc.y += 22;

      client.rows.forEach((r, ri) => {
        if (doc.y > doc.page.height - 90) {
          addPage();
          doc.y += 4;
        }
        const y = doc.y;
        if (ri % 2 === 0) doc.rect(margin, y, contentW, 22).fill("#f9fafb");
        const ctr = r.impressions > 0 ? (r.clicks / r.impressions) * 100 : 0;
        const vals = [
          r.campaign,
          money(r.spend),
          num(r.impressions),
          num(r.clicks),
          num(r.conversions),
          pct(ctr),
        ];
        doc.fillColor(dark).font("Helvetica").fontSize(9);
        vals.forEach((v, i) => {
          const x = margin + colW.slice(0, i).reduce((a, b) => a + b, 0);
          doc.text(v, x + 6, y + 6, { width: colW[i] - 12, ellipsis: true });
        });
        doc.y = y + 22;
      });
    }

    doc.end();
  });
}

function sanitizeColor(input: string | undefined): string {
  if (input && /^#[0-9a-fA-F]{6}$/.test(input)) return input;
  return "#2563eb";
}
